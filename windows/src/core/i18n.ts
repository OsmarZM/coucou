export type TextKey = keyof typeof PT_BR;
export function tr(key: TextKey): string { return PT_BR[key]; }
export function formatText(key: TextKey, values: Record<string, string | number>): string {
  return tr(key).replace(/\{([a-zA-Z]+)\}/g, (match, name: string) => String(values[name] ?? match));
}
export function stateLabel(state: BotStateName, ended = false): string {
  return tr(ended ? "state.ended" : `state.${state}`);
}
